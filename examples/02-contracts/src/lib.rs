//! Примеры к части 2/5: трейты, ассоциированные типы, const generics.
//!
//! Крейт зависит от `tdd_01_foundations`: неизменная часть словаря берётся
//! оттуда, уточнённая определяется в [`domain`]. Переименование в части 1
//! ломает сборку части 2 — это и нужно, иначе примеры разъедутся незаметно.
//!
//! Модули разбиты по доменным сущностям, а не по разделам статьи: уровень
//! стакана нужен и разделу про GAT, и разделу про const generics, а
//! `submit_batch` проходит сразу через три раздела — по разделам такой код
//! не режется. Разделы ложатся на модули так:
//!
//! | Раздел статьи        | Модули                          |
//! |----------------------|---------------------------------|
//! | Трейты как контракты | `exchange`, `order`, [`domain`] |
//! | Ассоциированные типы | `exchange`, `router`, `feed`    |
//! | Const generics       | `book`                          |
//! | Кульминация: CGP     | `cgp` (за feature-флагом)       |
//!
//! # Что здесь не проверено
//!
//! Утверждение статьи «двух `impl ExchangeClient for RestExchange` с разным
//! `ExchangeOrderId` не существует в принципе» доктестом не покрыто:
//! конфликтующие реализации жили бы в этом же крейте, а `compile_fail`-доктест
//! компилируется как внешний потребитель и до конфликта не доходит. Проверка
//! потребовала бы отдельного крейта, собираемого на провал.

